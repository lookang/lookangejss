        await move(page, W - 200, H//3, 900)
        await sleep(2)
        await move(page, W - 200, H//2, 600)
        await caption(page, "The information panel has guided activities, physics equations, and controls summary")
        await sleep(4)
        await move(page, W//2, H//2, 800)
        await sleep(2)
        await caption(page,
            "Bar Magnet & Compass Simulation — @lookang  |  iwant2study.org", 8000)
        # Final graceful pan
        await move(page, *s2p(0.5, 0.5), 1000)
        await sleep(2)
        await move(page, *s2p(-0.5, -0.5), 1200)
        await sleep(2)
