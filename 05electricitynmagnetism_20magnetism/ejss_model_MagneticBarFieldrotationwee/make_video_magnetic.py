"""
make_video_magnetic.py
======================
Playwright screen recording of the Bar Magnet & Compass simulation,
synchronised to narration_magnetic.mp3 (generated by generate_narration_magnetic.py).

Requirements:
  pip install playwright
  playwright install chromium

Output:
  magnetic_field_video.mp4   (1280 x 720, H.264 + AAC ~6 min)

Layout facts (1280x720 viewport, found by inspection):
  comboBox (magnet presets):   x=13, y=13, w=254, h=54  -> centre (140, 40)
  checkBox  (show Compass):    checkbox at (298, 38); label "show Compass" at (391, 36)
  checkBox2 (show Earth):      checkbox at (528, 38); label "show Earth" at (602, 36)
  resetButton:                 x=687, y=13, w=110, h=54  -> centre (742, 40)
  SVG simulation panel:        x=12.8, y=66.75, w=1254, h=648

Coordinate conversion (simulation -> pixels):
  px = 12.8  + 1254 * (sim_x + 1.5) / 3.0
  py = 66.75 + 648  * (1.0 - sim_y) / 2.0
  (x-range: -1.5 to 1.5;  y-range: -1.0 to 1.0, positive=up)
"""

import os, sys, asyncio, math, json
from pathlib import Path
from playwright.async_api import async_playwright

DIR      = Path(__file__).parent.resolve()
SIM_URL  = (DIR / "index.html").as_uri()
NARR_MP3 = DIR / "narration_magnetic.mp3"
OUT_MP4  = DIR / "magnetic_field_video.mp4"
W, H     = 1280, 720

# Section durations from Kokoro synthesis output
SEC_DUR = {
    "01_intro":                 23.5,
    "02_field_vectors":         33.2,
    "03_rotate_magnet_presets": 36.6,
    "04_drag_and_rotate":       41.4,
    "05_compass_probe":         46.0,
    "06_oscillation":           44.2,
    "07_earth_field":           43.2,
    "08_second_magnet":         44.6,
    "09_conclusion":            34.3,
}

# --- SVG canvas geometry (pixels) ---
SVG_X, SVG_Y = 12.8,  66.75
SVG_W, SVG_H = 1254.0, 648.0
SIM_XMAX, SIM_YMAX = 1.5, 1.0

def s2p(sx, sy):
    """Convert simulation (sx, sy) -> pixel (px, py)."""
    px = int(SVG_X + SVG_W * (sx + SIM_XMAX) / (2 * SIM_XMAX))
    py = int(SVG_Y + SVG_H * (SIM_YMAX - sy) / (2 * SIM_YMAX))
    return px, py

# --- Known control centres ---
CB_MAGNET_CX, CB_MAGNET_CY = 140, 40      # comboBox  (magnet presets)
CHK_COMPASS_X, CHK_COMPASS_Y = 298, 38    # checkBox  (show Compass)
CHK_EARTH_X,   CHK_EARTH_Y   = 528, 38    # checkBox2 (show Earth)
RESET_CX, RESET_CY = 742, 40              # resetButton

