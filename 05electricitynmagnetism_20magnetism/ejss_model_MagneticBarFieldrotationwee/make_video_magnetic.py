# ---------------------------------------------------------------------------
async def sleep(s):   await asyncio.sleep(s)

async def move(page, x, y, ms=400):
    await page.evaluate(f"window._C.move({x},{y},{ms})")
    await sleep(ms/1000 + 0.05)

async def ring(page, x, y):
    await page.evaluate(f"window._C.ring({x},{y})")

async def click_pos(page, x, y, ms=350):
    await move(page, x, y, ms)
    await page.evaluate("window._C.click()")
    await ring(page, x, y)
    await sleep(0.15)

async def caption(page, text, show_ms=4500):
    await page.evaluate(f"window._caption({repr(text)}, {show_ms})")

async def hide_cap(page):
    await page.evaluate("window._hideCaption()")

async def sim_set(page, obj):
    await page.evaluate(f"window._simSet({json.dumps(obj)})")
    await sleep(0.25)

async def sim_play(page):
    await page.evaluate("window._simPlay()")
    await sleep(0.2)

async def sim_pause(page):
    await page.evaluate("window._simPause()")
    await sleep(0.2)

async def sim_reset(page):
    await page.evaluate("window._simReset()")
    await sleep(0.4)

async def set_angle(page, deg):
    await page.evaluate(f"window._setAngle({deg})")
    await sleep(0.25)

async def magnet_to(page, sx, sy):
    """Move main magnet to simulation coords (sx, sy)."""
    await sim_set(page, {"xMagnet": sx, "yMagnet": sy,
                         "xMagnetDrag": sx, "yMagnetDrag": sy})

async def compass_to(page, sx, sy):
    """Move compass to simulation coords (sx, sy)."""
    await sim_set(page, {"xCompass": sx, "yCompass": sy,
                         "xCompassstore": sx, "yCompassstore": sy})

async def select_magnet_preset(page, option_text):
    """Select an option in comboBox (magnet presets)."""
    await click_pos(page, CB_MAGNET_CX, CB_MAGNET_CY, 400)
    await page.select_option("#comboBox", label=option_text)
    await sleep(0.5)

async def toggle_compass(page, enable: bool):
    """Set compass checkbox to desired state."""
    cb = page.locator("#checkBox\\.checkbox")
    is_on = await cb.is_checked()
    if is_on != enable:
        await click_pos(page, CHK_COMPASS_X, CHK_COMPASS_Y, 400)
        await cb.click()
        await sleep(0.3)
    # Also set via JS in case checkbox event didn't fire
    await sim_set(page, {"showCompass": enable})

async def toggle_earth(page, enable: bool):
    """Set earth checkbox to desired state."""
    cb = page.locator("#checkBox2\\.checkbox")
    is_on = await cb.is_checked()
    if is_on != enable:
        await click_pos(page, CHK_EARTH_X, CHK_EARTH_Y, 400)
        await cb.click()
        await sleep(0.3)
    await sim_set(page, {"earth": enable})

