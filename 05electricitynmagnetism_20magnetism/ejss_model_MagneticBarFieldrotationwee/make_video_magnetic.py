import time as _time

async def record_video():
    async with async_playwright() as pw:
        browser = await pw.chromium.launch(
            headless=True,
            args=["--disable-gpu","--no-sandbox","--disable-dev-shm-usage",
                  "--autoplay-policy=no-user-gesture-required"]
        )
        ctx = await browser.new_context(
            viewport={"width": W, "height": H},
            record_video_dir=str(DIR),
            record_video_size={"width": W, "height": H},
        )
        page = await ctx.new_page()

        print(f"Opening: {SIM_URL}")
        await page.goto(SIM_URL, wait_until="networkidle", timeout=30000)
        await sleep(3)

        await page.evaluate(INIT_JS)
        await sleep(0.5)

        # Start cursor in centre
        await move(page, W//2, H//2, 200)

        # ================================================================
        # 01 INTRO  (23.5 s)
        # ================================================================
        t0 = _time.time()
        await caption(page, "Bar Magnet & Compass — Magnetic Field Explorer")
        # Sweep cursor across top bar to introduce controls
        await move(page, CB_MAGNET_CX, CB_MAGNET_CY, 600)
        await ring(page, CB_MAGNET_CX, CB_MAGNET_CY)
        await sleep(1.5)
        await move(page, CHK_COMPASS_X, CHK_COMPASS_Y, 700)
        await ring(page, CHK_COMPASS_X, CHK_COMPASS_Y)
        await sleep(1.5)
        await move(page, CHK_EARTH_X, CHK_EARTH_Y, 700)
        await ring(page, CHK_EARTH_X, CHK_EARTH_Y)
        await sleep(1.5)
        await move(page, RESET_CX, RESET_CY, 700)
        await ring(page, RESET_CX, RESET_CY)
        await sleep(1.5)
        # Pan over the simulation canvas
        cx, cy = s2p(0, 0)
        await move(page, cx, cy, 900)
        await sleep(2)
        await move(page, *s2p(0.6, 0.5), 900)
        await sleep(2)
        await move(page, *s2p(-0.8, -0.4), 900)
        await sleep(2)
        await hide_cap(page)
        await sleep(max(0.1, SEC_DUR["01_intro"] - (_time.time()-t0)))

        # ================================================================
        # 02 FIELD VECTORS  (33.2 s)
        # ================================================================
        t0 = _time.time()
        await caption(page, "Field vectors emerge from the N pole and converge at the S pole")
        # Highlight the N-pole region
        px_n, py_n = s2p(0.3, 0.0)
        await move(page, px_n, py_n, 800)
        await ring(page, px_n, py_n)
        await sleep(2)
        # Trace an arc from N pole over top to S pole
        for sx in [0.5, 0.3, 0.0, -0.3, -0.5]:
            sy = 0.55 - abs(sx) * 0.1   # approximate arc
            await move(page, *s2p(sx, sy), 600)
            await sleep(0.5)
        await sleep(1)
        px_s, py_s = s2p(-0.3, 0.0)
        await move(page, px_s, py_s, 700)
        await ring(page, px_s, py_s)
        await sleep(2)
        await caption(page, "Field strength B falls as 1/r³ — arrows are longest near the poles")
        # Highlight close vs far
        await move(page, *s2p(0.25, 0.0), 700)
        await ring(page, *s2p(0.25, 0.0))
        await sleep(1.5)
        await move(page, *s2p(1.1, 0.0), 900)
        await ring(page, *s2p(1.1, 0.0))
        await sleep(2)
        await hide_cap(page)
        await sleep(max(0.1, SEC_DUR["02_field_vectors"] - (_time.time()-t0)))

        # ================================================================
        # 03 ROTATE VIA PRESET DROPDOWN  (36.6 s)
        # ================================================================
        t0 = _time.time()
        await caption(page, "Use the dropdown to rotate the magnet to preset orientations")
        await sleep(1.5)
        presets = [
            ("magnet points right", "Magnet RIGHT — N pole to the right, S pole to the left"),
            ("magnet points up",    "Magnet UP — entire field pattern rotates 90°"),
            ("magnet points left",  "Magnet LEFT — poles swap, arrows reverse direction"),
            ("magnet points down",  "Magnet DOWN — field rotates −90° from default"),
            ("magnet points right", "Back to the default orientation"),
        ]
        for opt, cap_text in presets:
            await select_magnet_preset(page, opt)
            await caption(page, cap_text, 4800)
            await sleep(5.5)
        await hide_cap(page)
        await sleep(max(0.1, SEC_DUR["03_rotate_magnet_presets"] - (_time.time()-t0)))

        # ================================================================
        # 04 DRAG & PRECISE ROTATION  (41.4 s)
        # ================================================================
        t0 = _time.time()
        await caption(page, "The magnet can be dragged to any position on the canvas")
        await sleep(1.5)
        # Move magnet to several positions; cursor follows
        moves = [
            (0.6,  0.4,  "Magnet offset to upper-right — field pattern shifts with it"),
            (-0.5, -0.3, "Magnet to lower-left — field re-centred around new position"),
            (0.0,  0.0,  "Back to centre"),
        ]
        for sx, sy, cap_text in moves:
            await magnet_to(page, sx, sy)
            px, py = s2p(sx, sy)
            await move(page, px, py, 700)
            await ring(page, px, py)
            await caption(page, cap_text, 4500)
            await sleep(5)
        await caption(page, "Use the angle dropdown (θ₁) to rotate in precise 10° steps")
        await sleep(1.5)
        for deg in [30, 60, 90, 120, 150, 180, 0]:
            await set_angle(page, deg)
            await move(page, *s2p(0.2*math.cos(math.radians(deg)),
                                   0.2*math.sin(math.radians(deg))), 300)
            await sleep(1.5)
        await caption(page, "The field pattern rotates smoothly — dipole symmetry always preserved")
        await sleep(4)
        await hide_cap(page)
        await sleep(max(0.1, SEC_DUR["04_drag_and_rotate"] - (_time.time()-t0)))

        # ================================================================
        # 05 COMPASS PROBE  (46.0 s)
        # ================================================================
        t0 = _time.time()
        await set_angle(page, 0)   # reset to pointing right
        await magnet_to(page, 0.0, 0.0)
        await toggle_compass(page, True)
        await caption(page, "Compass enabled — shows field direction and Bₓ, Bᵧ, |B|, θ readout")
        await sleep(3)
        probes = [
            (0.55,  0.0, "Axial position (right of N pole) — compass aligns with strong axial field"),
            (0.0,   0.7, "Equatorial above centre — compass points opposite to magnet direction"),
            (-0.55, 0.0, "Left of S pole — compass reverses, pointing into the south pole"),
            (0.0,  -0.7, "Below centre — symmetric to the equatorial position above"),
            (1.1,   0.0, "Far along the axis — field weaker, same direction"),
            (0.4,   0.4, "Off-axis — compass tilted by the combined Bx and By components"),
        ]
        for sx, sy, cap_text in probes:
            await compass_to(page, sx, sy)
            px, py = s2p(sx, sy)
            await move(page, px, py, 700)
            await ring(page, px, py)
            await caption(page, cap_text, 5000)
            await sleep(5.5)
        await hide_cap(page)
        await sleep(max(0.1, SEC_DUR["05_compass_probe"] - (_time.time()-t0)))

        # ================================================================
        # 06 COMPASS OSCILLATION  (44.2 s)
        # ================================================================
        t0 = _time.time()
        await compass_to(page, 0.5, 0.4)
        await caption(page, "Click Play — the compass is a damped harmonic oscillator")
        await sleep(2)
        await sim_play(page)
        await sleep(5)
        await caption(page, "It overshoots equilibrium, swings back, then settles — just like a real compass")
        await sleep(5)
        await sim_pause(page)
        await sleep(1)
        # Move to weaker field region
        await compass_to(page, 1.1, 0.6)
        px2, py2 = s2p(1.1, 0.6)
        await move(page, px2, py2, 700)
        await caption(page, "Weaker field region — slower oscillation (smaller restoring torque)")
        await sim_play(page)
        await sleep(5)
        await caption(page, "dω/dt = −k|B|·sin(δθ) − bω  — less |B| means lower frequency")
        await sleep(5)
        await sim_pause(page)
        await sleep(1)
        # Back to strong field
        await compass_to(page, 0.25, 0.0)
        await caption(page, "Back near the pole — rapid oscillation, strong restoring torque")
        await sim_play(page)
        await sleep(5)
        await sim_pause(page)
        await hide_cap(page)
        await sleep(max(0.1, SEC_DUR["06_oscillation"] - (_time.time()-t0)))

        # ================================================================
        # 07 EARTH FIELD  (43.2 s)
        # ================================================================
        t0 = _time.time()
        await toggle_compass(page, True)
        await toggle_earth(page, True)
        await click_pos(page, CHK_EARTH_X, CHK_EARTH_Y, 600)
        await caption(page, "Earth field ON — compass responds to bar magnet + Earth's geomagnetic field")
        await sleep(4)
        # Move compass far from magnet
        await compass_to(page, -1.1, 0.7)
        await move(page, *s2p(-1.1, 0.7), 800)
        await ring(page, *s2p(-1.1, 0.7))
        await caption(page, "Far from the magnet — Earth's field dominates, compass points north")
        await sleep(5)
