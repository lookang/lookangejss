def mux(webm: Path):
    import subprocess
    if not NARR_MP3.exists():
        print("WARNING: narration_magnetic.mp3 not found - saving video-only")
        cmd = ["ffmpeg","-y","-i",str(webm),"-c:v","libx264","-preset","fast",
               "-crf","22","-pix_fmt","yuv420p",str(OUT_MP4)]
    else:
        cmd = ["ffmpeg","-y",
               "-i",str(webm), "-i",str(NARR_MP3),
               "-c:v","libx264","-preset","fast","-crf","22","-pix_fmt","yuv420p",
               "-c:a","aac","-b:a","192k","-shortest",
               str(OUT_MP4)]
    print("Muxing ...")
    r = subprocess.run(cmd, capture_output=True, text=True)
    if r.returncode == 0:
        size = OUT_MP4.stat().st_size / (1024*1024)
        print(f"Done: {OUT_MP4}  ({size:.1f} MB)")
    else:
        print("ffmpeg error:\n", r.stderr[-2000:])


